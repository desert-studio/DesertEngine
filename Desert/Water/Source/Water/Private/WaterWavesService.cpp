    void WaterWavesService::BindAssetManager( const std::weak_ptr<Assets::AssetManager>& assets )
    {
        m_Assets = assets;
    }

    void WaterWavesService::Adopt( const Assets::AssetHandle&                    handle,
                                   const Assets::Asset<Assets::WaterWavesAsset>& asset )
    {
        // The set's waves are a pure function of its generator and the wind's angle (UE RecomputeWaves): kept
        // here, generated by Get for the wind the set is raised by. The angle only turns every wave, so the
        // steepness sum below is the same for every wind and is checked once, at +X.
        const Water::GerstnerWaveGenerator& generator = asset->GetData().Generator;
        const std::vector<Water::GerstnerWave> waves  = Water::GenerateGerstnerWaves( generator, 0.0f );

        // A sum of Gerstner waves stays a surface only while the horizontal squeeze of all of them together cannot
        // pass the particle's own spacing: sum of Q k A (= each wave's Steepness) <= 1 (Tessendorf 2001 sec. 4.4;
        // UE's generator does not check it and its steep presets loop). Past it the mesh folds through itself
        // where the crests line up, and the whitecaps (the Jacobian below the material's threshold) are drawn from
        // folds rather than from crests about to break. Refused out loud: the set's author lowers the steepness.
        float steepness = 0.0f;
        for ( const Water::GerstnerWave& wave : waves )
            steepness += wave.Steepness;
        if ( steepness > 1.0f )
        {
            const std::string why =
                 std::format( "its waves' steepness sums to {:.2f} (Q k A summed over {} waves); a "
                              "Gerstner sum folds through itself past 1 - lower SmallWaveSteepness/"
                              "LargeWaveSteepness",
                              steepness, waves.size() );
            Fail( handle, why );
            return;
        }
        ++m_ShapeSerial;
        m_Failed.erase( handle );
        m_Ready.erase( handle );
        m_Spectra.erase( handle );
        m_Generators[handle] = std::make_shared<const Water::GerstnerWaveGenerator>( generator );

        // An FFT set's ocean: its h0 cascades are a pure function of the FFT block, its seed and the scene's wind
        // (SetWind), built by GetSpectrum (4 x 256^2 texels) when the wind changes and uploaded by the water
        // renderer when the pointer does; the parse already refused a block the spectrum cannot honour.
        if ( asset->GetData().Source == Water::WaterWaveSource::FFT )
            m_Shapes[handle] = asset->GetData().FFT;
        else
            m_Shapes.erase( handle );
    }

    void WaterWavesService::Fail( const Assets::AssetHandle& handle, const std::string& why )
    {
        LOG_ERROR( "[Water] Wave set {} is refused: {}{}", static_cast<uint64_t>( handle ), why,
                   m_Generators.contains( handle ) ? " - its last read waves are kept" : "" );
        if ( m_Generators.contains( handle ) )
            return;
        ++m_ShapeSerial;
        m_Failed[handle] = why;
    }

    void WaterWavesService::SetWind( const Assets::AssetHandle& handle, const glm::vec2& velocityXZ )
    {
        const float speed = glm::length( velocityXZ );
        if ( !std::isfinite( speed ) )
            return; // WindAt sums finite sources; a non-finite sum is no wind to raise a sea by
        Water::FFTOceanWind wind;
        wind.Speed = std::round( speed / 10.0f ) * 10.0f;
        if ( wind.Speed > 0.0f )
            wind.AngleDeg = std::round( glm::degrees( std::atan2( velocityXZ.y, velocityXZ.x ) ) * 2.0f ) * 0.5f;
        m_Winds[handle] = wind;
    }

    void WaterWavesService::FollowWrites()
    {
        if ( Assets::ContentRegistry::WriteSerial() == m_SeenWrites )
            return;
        const auto written =
             Assets::ContentRegistry::WrittenSince( Common::Content::ContentKind::WaterWaves, m_SeenWrites );
        m_SeenWrites      = written.Serial;
        const auto assets = m_Assets.lock();
        for ( const auto& row : written.Rows )
        {
            const Assets::AssetHandle handle = row.Handle;
            // Only a set this service has read or refused: one never asked for is read when first asked. A read
            // still in flight is left to land; it reads the file as it is when the loader opens it.
            if ( !m_Generators.contains( handle ) && !m_Failed.contains( handle ) )
                continue;
            if ( m_Requests.contains( handle ) )
                continue;
            Assets::Asset<Assets::WaterWavesAsset> asset;
            if ( assets )
                asset = assets->ProbeByHandle<Assets::WaterWavesAsset>( handle );
            if ( asset == nullptr )
            {
                Read( handle ); // not resident any more: read afresh, the waves it had stand until it lands
                continue;
            }
            if ( const auto reread = asset->LoadFromFile(); !reread )
            {
                Fail( handle, reread.GetError() );
                continue;
            }
            LOG_INFO( "[Water] Wave set {} was saved: its waves are rebuilt.", static_cast<uint64_t>( handle ) );
            Adopt( handle, asset );
        }
    }

    WaveSetKind WaterWavesService::KindOf( const Assets::AssetHandle& handle )
    {
        Request( handle );
        if ( m_Generators.contains( handle ) )
            return m_Shapes.contains( handle ) ? WaveSetKind::FFT : WaveSetKind::Gerstner;
        return m_Failed.contains( handle ) ? WaveSetKind::Failed : WaveSetKind::Pending;
    }

    uint64_t WaterWavesService::ShapeSerial()
    {
        FollowWrites();
        return m_ShapeSerial;
    }

    float WaterWavesService::WindAngleOf( const Assets::AssetHandle& handle ) const
    {
        const auto wound = m_Winds.find( handle );
        return wound == m_Winds.end() ? 0.0f : wound->second.AngleDeg;
    }

    void WaterWavesService::Request( const Assets::AssetHandle& handle )
    {
        FollowWrites();
        if ( !m_Generators.contains( handle ) && !m_Failed.contains( handle ) && !m_Requests.contains( handle ) )
            Read( handle );
    }

    void WaterWavesService::Read( const Assets::AssetHandle& handle )
    {
        auto created = Assets::CreateFromRegistryRow<Assets::WaterWavesAsset>(
             m_Assets, handle, Common::Content::ContentKind::WaterWaves );
        if ( !created )
        {
            Fail( handle, created.GetError() );
            return;
        }
        if ( created.GetValue()->IsReadyForUse() )
        {
            Adopt( handle, created.GetValue() );
            return;
        }
        m_Requests[handle] = Assets::AsyncAssetLoader::Get().Request(
             created.GetValue(),
             [this, handle]( const Assets::Asset<Assets::AssetBase>& loaded,
                                   const Assets::LoadOutcome outcome, const std::string& error )
             {
                 m_Requests.erase( handle );
                 if ( outcome == Assets::LoadOutcome::Loaded )
                     Adopt( handle, std::static_pointer_cast<Assets::WaterWavesAsset>( loaded ) );
                 else
                     Fail( handle, error );
             },
             [this, handle] { m_Requests.erase( handle ); } );
    }

    Common::ResultStr<WaterWavesService::Waves> WaterWavesService::Get( const Assets::AssetHandle& handle )
    {
        Request( handle );
        if ( const auto failed = m_Failed.find( handle ); failed != m_Failed.end() )
            return Common::MakeError<Waves>( failed->second );
        const auto generator = m_Generators.find( handle );
        if ( generator == m_Generators.end() )
            return Common::MakeSuccess( Waves{} );
        // Rebuilt only when the wind turned (SetWind quantises it to 0.5 deg): the same pattern as GetSpectrum.
        const float angle = WindAngleOf( handle );
        BuiltWaves& built = m_Ready[handle];
        if ( built.Set == nullptr || built.AngleDeg != angle )
            built = { std::make_shared<const std::vector<Water::GerstnerWave>>(
                           Water::GenerateGerstnerWaves( *generator->second, angle ) ),
                      angle };
        return Common::MakeSuccess( built.Set );
    }

    Common::ResultStr<WaterWavesService::Spectrum> WaterWavesService::GetSpectrum( const Assets::AssetHandle& handle )
    {
        Request( handle );
        if ( const auto failed = m_Failed.find( handle ); failed != m_Failed.end() )
            return Common::MakeError<Spectrum>( failed->second );
        const auto shape = m_Shapes.find( handle );
        if ( shape == m_Shapes.end() )
            return Common::MakeSuccess( Spectrum{} ); // a Gerstner set, or still loading
        // The set's wind this frame (still air until a body states one); the spectrum is rebuilt only when it
        // differs from the wind the current one was raised by.
        Water::FFTOceanWind wind; // still air until a body states one
        if ( const auto wound = m_Winds.find( handle ); wound != m_Winds.end() )
            wind = wound->second;
        Spectrum& built = m_Spectra[handle];
        if ( built == nullptr || !( built->Wind == wind ) )
        {
            auto spectrum = std::make_shared<const Water::FFTOceanSpectrum>(
                 Water::BuildFFTOceanSpectrum( shape->second, wind ) );
            for ( const Water::FFTOceanCascade& cascade : spectrum->Cascades )
                if ( cascade.H0.size() != static_cast<size_t>( Water::kFFTOceanResolution ) * Water::kFFTOceanResolution )
                {
                    LOG_ERROR( "[Water] Wave set {}: its FFT spectrum has {} texels in a cascade, not {} a side - its "
                               "Gerstner generator is its sea",
                               static_cast<uint64_t>( handle ), cascade.H0.size(), Water::kFFTOceanResolution );
                    m_Spectra.erase( handle );
                    m_Shapes.erase( handle );
                    ++m_ShapeSerial;
                    return Common::MakeSuccess( Spectrum{} );
                }
            built = std::move( spectrum );
        }
        return Common::MakeSuccess( built );
    }

    void WaterWavesService::Clear()
    {
        m_Requests.clear();
        m_Generators.clear();
        m_Ready.clear();
        m_Spectra.clear();
        m_Shapes.clear();
        m_Winds.clear();
        m_Failed.clear();
        ++m_ShapeSerial;
    }

    WaterWavesService* GetWaterWavesService()
    {
        static WaterWavesService service;
        return &service;
    }
