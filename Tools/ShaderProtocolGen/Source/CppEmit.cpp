#include "GlslEmit.hpp"

#include <algorithm>
#include <format>
#include <string>
#include <vector>

namespace Desert::ShaderProtocolGen
{
    namespace
    {
        // The text as a char array of decimal bytes: no MSVC string-literal limit (16 KB a piece, 64 KB joined).
        std::string CharArray( const std::string_view name, const std::string_view text )
        {
            std::string out = std::format( "        constexpr char {}[] = {{", name );
            for ( size_t i = 0; i < text.size(); ++i )
            {
                if ( i % 24 == 0 )
                    out += "\n            ";
                out += std::format( "{},", static_cast<int>( static_cast<signed char>( text[i] ) ) );
            }
            out += "\n        };\n";
            return out;
        }

        std::string StringLiteral( const std::string_view text )
        {
            std::string out = "\"";
            for ( const char c : text )
            {
                if ( c == '"' || c == '\\' )
                    out += '\\';
                out += c;
            }
            return out + "\"";
        }
    } // namespace

    std::string EmitCppTable( const std::span<const GeneratedInclude> includes,
                              const std::span<const std::string_view> vertexInputNames )
    {
        std::vector<const GeneratedInclude*> sorted;
        for ( const GeneratedInclude& include : includes )
            sorted.push_back( &include );
        std::ranges::sort( sorted, {}, []( const GeneratedInclude* g ) { return g->Decl->Path; } );
        std::vector<std::string_view> names( vertexInputNames.begin(), vertexInputNames.end() );
        std::ranges::sort( names );
        names.erase( std::unique( names.begin(), names.end() ), names.end() );

        std::string cpp = "// GENERATED by Tools/ShaderProtocolGen from the C++ shader layout declarations "
                          "(Graphic/ShaderProtocols/ShaderProtocol.hpp); never edited by hand.\n"
                          "#include <Engine/Core/ShaderCompiler/GeneratedShaderIncludes.hpp>\n\n"
                          "#include <algorithm>\n#include <array>\n#include <string_view>\n\n"
                          "namespace Desert::Core\n{\n    namespace\n    {\n";
        for ( size_t i = 0; i < sorted.size(); ++i )
            cpp += CharArray( std::format( "kText{}", i ), sorted[i]->Text );

        cpp += "\n        // Sorted by path: FindGeneratedShaderInclude is a binary search.\n"
               "        constexpr std::array<GeneratedShaderInclude, " +
               std::to_string( sorted.size() ) + "> kIncludes{ {\n";
        for ( size_t i = 0; i < sorted.size(); ++i )
            cpp += std::format( "            {{ {}, std::string_view( kText{}, sizeof( kText{} ) ), {}ull }},\n",
                                StringLiteral( sorted[i]->Decl->Path ), i, i, sorted[i]->Hash );
        cpp += "        } };\n\n        constexpr std::array<std::string_view, " + std::to_string( names.size() ) +
               "> kVertexInputNames{ {\n";
        for ( const std::string_view name : names )
            cpp += std::format( "            {},\n", StringLiteral( name ) );
        cpp += "        } };\n    } // namespace\n\n";

        cpp += "    const GeneratedShaderInclude* FindGeneratedShaderInclude( const std::string_view path ) "
               "noexcept\n"
               "    {\n"
               "        const auto it = std::lower_bound( kIncludes.begin(), kIncludes.end(), path,\n"
               "                                           []( const GeneratedShaderInclude& include, "
               "const std::string_view p ) { return include.Path < p; } );\n"
               "        return it != kIncludes.end() && it->Path == path ? &*it : nullptr;\n"
               "    }\n\n"
               "    std::span<const GeneratedShaderInclude> GeneratedShaderIncludes() noexcept\n"
               "    {\n"
               "        return kIncludes;\n"
               "    }\n\n"
               "    bool IsGeneratedVertexInputName( const std::string_view name ) noexcept\n"
               "    {\n"
               "        return std::binary_search( kVertexInputNames.begin(), kVertexInputNames.end(), "
               "name );\n"
               "    }\n"
               "} // namespace Desert::Core\n";
        return cpp;
    }
} // namespace Desert::ShaderProtocolGen
